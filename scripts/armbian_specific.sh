#!/bin/bash
###############################################################################
# armbian_specific.sh
# 
# Armbian-Specific Optimizations for ICMP Tunnel Server
# 
# Includes:
# - Performance tuning for ARM processors
# - Network buffer optimizations
# - Kernel parameter adjustments
# - Firewall optimization for low-power devices
# 
# Usage: sudo ./scripts/armbian_specific.sh
###############################################################################

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo "╔════════════════════════════════════════════════════════════╗"
echo "║      Armbian-Specific ICMP Tunnel Optimizations            ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""

# Check if running as root
if [ "$EUID" -ne 0 ]; then
    echo -e "${RED}ERROR: This script must be run as root${NC}"
    echo "Usage: sudo $0"
    exit 1
fi

# Check if running on ARM
ARCH=$(uname -m)
echo "Detected architecture: $ARCH"
if [[ ! "$ARCH" =~ ^(arm|aarch64) ]]; then
    echo -e "${YELLOW}WARNING: This system does not appear to be ARM-based${NC}"
    echo "Optimizations are designed for Armbian/ARM devices"
    echo "Continue anyway? (y/n)"
    read -r response
    if [[ ! "$response" =~ ^[Yy]$ ]]; then
        exit 0
    fi
fi
echo ""

# Step 1: Network buffer optimizations
echo -e "${YELLOW}[1/5]${NC} Optimizing network buffers for low-power device..."

# Increase network buffers (but not too much for low-memory devices)
sysctl -w net.core.rmem_max=2097152 >/dev/null 2>&1
sysctl -w net.core.wmem_max=2097152 >/dev/null 2>&1
sysctl -w net.core.rmem_default=262144 >/dev/null 2>&1
sysctl -w net.core.wmem_default=262144 >/dev/null 2>&1

echo -e "${GREEN}  ✓ Network buffers optimized${NC}"

# Step 2: Reduce TCP keepalive for faster connection detection
echo -e "${YELLOW}[2/5]${NC} Tuning TCP parameters..."

sysctl -w net.ipv4.tcp_keepalive_time=600 >/dev/null 2>&1
sysctl -w net.ipv4.tcp_keepalive_intvl=30 >/dev/null 2>&1
sysctl -w net.ipv4.tcp_keepalive_probes=3 >/dev/null 2>&1

echo -e "${GREEN}  ✓ TCP parameters tuned${NC}"

# Step 3: Optimize for ICMP traffic
echo -e "${YELLOW}[3/5]${NC} Optimizing ICMP handling..."

# Increase ICMP rate limit (allow more ICMP packets per second)
sysctl -w net.ipv4.icmp_ratelimit=0 >/dev/null 2>&1
sysctl -w net.ipv4.icmp_ratemask=0 >/dev/null 2>&1

echo -e "${GREEN}  ✓ ICMP rate limiting disabled${NC}"

# Step 4: Connection tracking optimizations
echo -e "${YELLOW}[4/5]${NC} Optimizing connection tracking..."

# Reduce conntrack table size for low-memory devices
sysctl -w net.netfilter.nf_conntrack_max=32768 >/dev/null 2>&1
sysctl -w net.netfilter.nf_conntrack_tcp_timeout_established=3600 >/dev/null 2>&1

echo -e "${GREEN}  ✓ Connection tracking optimized${NC}"

# Step 5: Enable conntrack helper for FTP, SIP, etc. (optional)
echo -e "${YELLOW}[5/5]${NC} Configuring protocol helpers..."

# Note: Some protocols may need helpers enabled
# sysctl -w net.netfilter.nf_conntrack_helper=1

echo "  Protocol helpers left at default (disabled for security)"
echo -e "${GREEN}  ✓ Configuration complete${NC}"

# Display current optimized settings
echo ""
echo "╔════════════════════════════════════════════════════════════╗"
echo "║           Current Optimized Settings                       ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""
echo "Network Buffers:"
echo "  rmem_max:     $(sysctl -n net.core.rmem_max)"
echo "  wmem_max:     $(sysctl -n net.core.wmem_max)"
echo ""
echo "TCP Keepalive:"
echo "  keepalive_time:   $(sysctl -n net.ipv4.tcp_keepalive_time)s"
echo "  keepalive_intvl:  $(sysctl -n net.ipv4.tcp_keepalive_intvl)s"
echo ""
echo "ICMP:"
echo "  ratelimit:    $(sysctl -n net.ipv4.icmp_ratelimit)"
echo ""
echo "Connection Tracking:"
echo "  conntrack_max: $(sysctl -n net.netfilter.nf_conntrack_max 2>/dev/null || echo 'N/A')"
echo ""

# Make settings persistent
echo -e "${YELLOW}Making settings persistent...${NC}"

SYSCTL_CONF="/etc/sysctl.d/99-icmptunnel.conf"
cat > $SYSCTL_CONF << EOF
# ICMP Tunnel Optimizations for Armbian
# Generated by armbian_specific.sh

# Network buffers
net.core.rmem_max=2097152
net.core.wmem_max=2097152
net.core.rmem_default=262144
net.core.wmem_default=262144

# TCP keepalive
net.ipv4.tcp_keepalive_time=600
net.ipv4.tcp_keepalive_intvl=30
net.ipv4.tcp_keepalive_probes=3

# ICMP optimizations
net.ipv4.icmp_ratelimit=0
net.ipv4.icmp_ratemask=0

# Connection tracking
net.netfilter.nf_conntrack_max=32768
net.netfilter.nf_conntrack_tcp_timeout_established=3600
EOF

echo -e "${GREEN}  ✓ Settings saved to $SYSCTL_CONF${NC}"
echo "  These will persist across reboots"

echo ""
echo "╔════════════════════════════════════════════════════════════╗"
echo "║        Armbian Optimizations Complete!                     ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""
echo -e "${GREEN}✓ Armbian system optimized for ICMP tunneling${NC}"
echo ""
echo "Note: Optimizations are active immediately and will persist after reboot"
echo ""

exit 0
